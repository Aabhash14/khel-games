  const NE_DIGITS = '०१२३४५६७८९';
  let lang = 'en';
  try {
    const saved = localStorage.getItem('ipla.lang') || localStorage.getItem('khel.lang');
    if (saved === 'ne' || saved === 'en') lang = saved;
  } catch { /* private mode */ }

  const getLang = () => lang;
  function setLang(l) {
    lang = l;
    try { localStorage.setItem('ipla.lang', l); } catch { /* fine */ }
  }
  const num = (n) => (lang === 'ne' ? String(n).replace(/\d/g, (d) => NE_DIGITS[d]) : String(n));
  function t(key, vars = {}) {
    const s = S[lang][key] ?? S.en[key] ?? key;
    return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] == null ? '' : typeof vars[k] === 'number' ? num(vars[k]) : vars[k]));
  }

  // Money is stored in lakh. ₹27 Cr, ₹26.75 Cr, ₹75 L.
  function money(lakh) {
    if (lakh >= 100) {
      const cr = (lakh / 100).toFixed(2).replace(/\.?0+$/, '');
      return lang === 'ne' ? `₹${num(cr)} करोड` : `₹${cr} Cr`;
    }
    return lang === 'ne' ? `₹${num(lakh)} लाख` : `₹${lakh} L`;
  }
  // Short form for tight spots: 27.5 / 0.75
  const crShort = (lakh) => num((lakh / 100).toFixed(2).replace(/\.?0+$/, '') || '0');

  function ordinal(n) {
    if (lang === 'ne') return `${num(n)} औं`;
    const s = ['th', 'st', 'nd', 'rd']; const v = n % 100;
    return n + (s[(v - 20) % 10] || s[v] || s[0]);
  }

  function setName(set) {
    const base = t(`set_${set.key}`);
    return set.capped === false ? t('uncappedSet', { s: base }) : base;
  }

  function applyStatic(root = document) {
    root.querySelectorAll('[data-t]').forEach((el) => { el.textContent = t(el.dataset.t, { y: 2027 }); });
    document.documentElement.lang = lang === 'ne' ? 'ne' : 'en';
    document.querySelectorAll('[data-set-lang]').forEach((b) => b.setAttribute('aria-pressed', String(b.dataset.setLang === lang)));
  }
  IPLA.i18n = { getLang, setLang, num, t, money, crShort, ordinal, setName, applyStatic };
