const NE_DIGITS = '०१२३४५६७८९';
let lang = 'en';
try { lang = localStorage.getItem('duo.lang') || ((navigator.language || '').startsWith('ne') ? 'ne' : 'en'); } catch { /* private mode */ }

export const getLang = () => lang;
export function setLang(l) {
  lang = l === 'ne' ? 'ne' : 'en';
  try { localStorage.setItem('duo.lang', lang); } catch { /* fine */ }
  document.documentElement.lang = lang;
}
export const num = (n) => (lang === 'ne' ? String(n).replace(/\d/g, (d) => NE_DIGITS[d]) : String(n));
export function t(key, vars = {}) {
  const s = S[lang][key] ?? S.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] == null ? '' : typeof vars[k] === 'number' ? num(vars[k]) : vars[k]));
}
export function applyStatic(root = document) {
  root.querySelectorAll('[data-t]').forEach((el) => { el.textContent = t(el.dataset.t); });
}
