const NE_DIGITS = '०१२३४५६७८९';
let lang = 'en';
try {
  const saved = localStorage.getItem('tuin.lang') || localStorage.getItem('khel.lang');
  lang = saved === 'ne' || saved === 'en' ? saved : (navigator.language || '').toLowerCase().startsWith('ne') ? 'ne' : 'en';
} catch { /* private mode */ }

export const getLang = () => lang;
export function setLang(l) {
  lang = l;
  try { localStorage.setItem('tuin.lang', l); } catch { /* fine */ }
}
export const num = (n) => (lang === 'ne' ? String(n).replace(/\d/g, (d) => NE_DIGITS[d]) : String(n));
export function t(key, vars = {}) {
  let s = S[lang][key] ?? S.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, typeof v === 'number' ? num(v) : v);
  return s;
}
/** Cast member's name in the current language. English animal names read better lower-case mid-sentence. */
export const nameOf = (c, mid = false) => (lang === 'ne' ? c.ne : (mid && !c.human ? c.en.toLowerCase() : c.en));
