const NE_DIGITS = '०१२३४५६७८९';
let lang = 'en';
try {
  const saved = localStorage.getItem('imposter.lang') || localStorage.getItem('khel.lang');
  lang = saved === 'ne' || saved === 'en' ? saved : (navigator.language || '').toLowerCase().startsWith('ne') ? 'ne' : 'en';
} catch { /* private mode */ }

export const getLang = () => lang;
export function setLang(l) {
  lang = l;
  try { localStorage.setItem('imposter.lang', l); } catch { /* fine */ }
}
export const num = (n) => (lang === 'ne' ? String(n).replace(/\d/g, (d) => NE_DIGITS[d]) : String(n));
export function t(key, vars = {}) {
  let s = S[lang][key] ?? S.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, typeof v === 'number' ? num(v) : v);
  return s;
}
/** A {en, ne} object in the current language. */
export const L = (o) => (o ? o[lang] ?? o.en : '');
