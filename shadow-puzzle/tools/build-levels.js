// Rebuild ../levels.js:  node tools/build-levels.js   (edit the L list below to change words)
const { F5, F7, solve } = require("./glyphs.js");
const ROTS = (() => { // same order as gen.js
  const perms = [[0,1,2],[0,2,1],[1,0,2],[1,2,0],[2,0,1],[2,1,0]], out = [];
  for (const p of perms) for (let s = 0; s < 8; s++) {
    const m = [[0,0,0],[0,0,0],[0,0,0]]; const sg = [s&1?-1:1, s&2?-1:1, s&4?-1:1];
    for (let r = 0; r < 3; r++) m[r][p[r]] = sg[r];
    const det = m[0][0]*(m[1][1]*m[2][2]-m[1][2]*m[2][1]) - m[0][1]*(m[1][0]*m[2][2]-m[1][2]*m[2][0]) + m[0][2]*(m[1][0]*m[2][1]-m[1][1]*m[2][0]);
    if (det === 1) out.push(m);
  } return out; })();
const L = [["A",F7,[5,7,5]],["HI",F7,[5,7,5]],["GO",F7,[5,7,5]],["OK",F7,[5,7,5]],["UP",F7,[5,7,5]],["NO",F7,[5,7,5]],
  ["HAT",F5,[5,5,5]],["SUN",F5,[5,5,5]],["TEA",F5,[5,5,5]],["ELF",F5,[5,5,5]],["AIR",F5,[5,5,5]],["IVY",F5,[5,5,5]]];
const levels = L.map(([w, f, d]) => { const r = solve(w, f, d); if (!r) throw w;
  return { word: w, dims: d, vox: r.vox.map(v => v.join("")).join(" "), targets: r.rots.map(i => ROTS[i].flat()) }; });
const src = "// Generated by the Umbra level generator: voxel sculptures whose axis shadows spell each word.\n" +
  "// vox: space-separated i j k voxel indices; targets: row-major 3x3 rotation that faces each letter to the lamp.\n" +
  "window.UMBRA_LEVELS = [\n" + levels.map(l => "  " + JSON.stringify(l)).join(",\n") + "\n];\n";
require("fs").writeFileSync(require("path").join(__dirname, "..", "levels.js"), src);
